def extras():
    body = intro('404', 'Page not found', 'The page may have moved. Browse publications and research notes, or return to the homepage.')
    body += '<div class="button-row">' + link('/index.html', 'Home', 'button') + link('/publications.html', 'Publications', 'button button-secondary') + link('/blog/index.html', 'Notes & resources', 'button button-secondary') + '</div>'
    page('404.html', 'Page not found', 'Find publications, research notes and contact information on the academic homepage of Xian-Zhang Chen.', body, extra_head='<meta name="robots" content="noindex">')
    urls = sorted({canonical(p) for p in PAGES if p not in ('404.html', 'blog-post.html') and not p.startswith('blog/posts/')})
    put('sitemap.xml', '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + '\n'.join(f'  <url><loc>{xml_escape(url)}</loc><lastmod>{PROFILE["updated"]}</lastmod></url>' for url in urls) + '\n</urlset>')
    put('robots.txt', 'User-agent: *\nAllow: /\nSitemap: ' + SITE + '/sitemap.xml')
    entries = []
    for paper in PUBLICATIONS:
        def bib(value):
            return str(value).replace('\\', r'\textbackslash{}').replace('&', r'\&').replace('%', r'\%').replace('_', r'\_')
        fields = [('title', '{' + bib(paper['title']) + '}'), ('author', ' and '.join(bib(a) for a in paper['authors'])),
                  ('year', str(paper['year'])), ('journal', bib(paper['venue'])), ('doi', paper['doi']), ('url', paper['url'])]
        if paper['status'] == 'preprint':
            fields += [('archivePrefix', 'arXiv'), ('eprint', paper['citation'].removeprefix('arXiv:'))]
        else:
            match = re.search(r'\b(\d+),\s*([\w]+)\s*\(', paper['citation'])
            if match:
                fields += [('volume', match[1]), ('pages', match[2])]
            elif 'e00004' in paper['citation']:
                fields += [('pages', 'e00004')]
        entries.append('@article{' + paper['id'] + ',\n' + ',\n'.join('  ' + key + ' = {' + value + '}' for key, value in fields if value) + '\n}')
    put('data/publications.bib', '\n\n'.join(entries))
    put('data/right_sidebar.html', '<section class="rightbar-section"><h2>Recent updates</h2>' + news_list(NEWS[:2]) + '</section><section class="rightbar-section"><h2>Contact</h2><p>' + link('mailto:' + PROFILE['email'], esc(PROFILE['email'])) + '</p></section>')
    put('data/build-manifest.json', json.dumps({'pages': sorted(PAGES), 'generated': sorted(list(OUTPUTS) + ['data/build-manifest.json']), 'updated': PROFILE['updated']}, ensure_ascii=False, indent=2))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check committed outputs without writing files.')
    args = parser.parse_args()
    global PROFILE, PUBLICATIONS, NEWS, POSTS, APPEARANCE
    PROFILE = load('data/profile.json')
    PUBLICATIONS = load('data/publications.json')
    NEWS = sorted(load('data/news.json'), key=lambda p: p['date'], reverse=True)
    POSTS = load('blog/posts/index.json')
    APPEARANCE = load('data/site-appearance.json')
    home()
    about()
    publications()
    news()
    contact()
    blog()
    appearance()
    extras()
    changed = []
    for name, value in OUTPUTS.items():
        target = ROOT / name
        if not target.is_file() or target.read_text(encoding='utf-8') != value:
            changed.append(name)
            if not args.check:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(value, encoding='utf-8')
    if args.check and changed:
        raise SystemExit('Generated files are out of date; run python3 scripts/build_site.py:\n' + '\n'.join(changed))
    print(f'{"Checked" if args.check else "Built"} {len(PAGES)} HTML pages; {len(changed)} {"stale" if args.check else "updated"} files.')


if __name__ == '__main__':
    main()
