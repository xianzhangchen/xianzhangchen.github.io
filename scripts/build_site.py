class HeadingParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.headings = []
        self.current = None

    def handle_starttag(self, tag, attrs):
        if tag == 'h2':
            self.current = [dict(attrs).get('id', ''), '']

    def handle_data(self, data):
        if self.current is not None:
            self.current[1] += data

    def handle_endtag(self, tag):
        if tag == 'h2' and self.current is not None:
            self.headings.append(self.current)
            self.current = None


def article_content(item):
    source = ROOT / item['content']
    if not source.is_file():
        raise ValueError('Article source missing: ' + item['content'])
    text = source.read_text(encoding='utf-8')
    if source.suffix == '.md':
        if not shutil.which('pandoc'):
            raise SystemExit('Pandoc 3.x is required to build Markdown articles. Install Pandoc, then run this command again.')
        text = re.sub(r'\A---\r?\n.*?\r?\n---\r?\n', '', text, count=1, flags=re.S)
        text = subprocess.run(['pandoc', '--from=markdown+tex_math_dollars+fenced_code_blocks+pipe_tables',
                               '--to=html5', '--mathml', '--syntax-highlighting=none', '--wrap=none'],
                              input=text, text=True, capture_output=True, check=True).stdout
        text = re.sub(r'<(/?)h1(?=[\s>])', r'<\1h2', text)
    if re.search(r'<(?:script|iframe)\b|(?:href|src)\s*=\s*[\'\"]\s*javascript:', text, re.I):
        raise ValueError('Unsafe active content in article: ' + item['content'])
    return text


def post_cover(item):
    cover = item.get('cover', {})
    if not cover.get('enabled', True):
        return ''
    if cover.get('src'):
        return f'<figure class="post-cover"><img src="{esc(cover["src"])}" alt="{esc(cover.get("alt", item["title"]))}" loading="lazy" width="940" height="400"></figure>'
    return '<figure class="post-cover" aria-hidden="true"><div class="post-cover-empty"></div></figure>'


