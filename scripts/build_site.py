def esc(value):
    return html.escape(str(value), quote=True)


def load(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def link(url, label, cls=""):
    if not url:
        return ""
    if urlsplit(url).scheme not in ("", "http", "https", "mailto"):
        raise ValueError("Unsupported URL protocol: " + url)
    return f'<a href="{esc(url)}"' + (f' class="{esc(cls)}"' if cls else "") + f'>{label}</a>'


def canonical(path):
    if path == "index.html":
        return SITE + "/"
    if path == "blog/index.html":
        return SITE + "/blog/"
    return SITE + "/" + path


def put(path, value):
    OUTPUTS[path] = re.sub(r'(?m)^[ \t]+$', '', value).rstrip() + "\n"


